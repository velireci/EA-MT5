#!/usr/bin/env python3
"""T003 offline replay of a candle CSV written by XauUsdH4Bias.mq5 (InpExportCandles = true).

Purpose: reproduce, in the Python MODEL (tests/t003_reference_test.py), the evaluation the EA made
on a real MT5 series, and print the same diagnostics (DIAG1..DIAG8) the EA prints in the Experts
log, so that a LIMITED_BY_HISTORY result can be explained and later turned into a test.

What it proves and what it does not:
  * It runs the PYTHON MODEL of the PROPOSED rules on the exported closed bars. The model is the
    reference of the MQL5 code (same cases are compared in T003_LogicTest.mq5), but a match here
    is not a compilation or an MT5 run of anything.
  * The CSV header carries the flag and reason the EA computed (result_flag / result_reason). This
    tool compares them with its own result and prints REPRODUCED or NOT REPRODUCED. If they do
    not match, the model and the MQL5 code disagree on this series (or the CSV is incomplete):
    send the CSV back, that is the finding.
  * No data is invented: the tool only reads the file it is given. A file whose header says
    'source=SYNTHETIC ...' was generated by the tests and is NOT market data.

Usage:
  python3 tests/t003_replay_csv.py velo_t003_diag_XAUUSD_202610052000.csv
  python3 tests/t003_replay_csv.py FILE --rebuild 2000 --lookback 300      other depth (offline only)
  python3 tests/t003_replay_csv.py FILE --asof "2026.10.04 12:00"          only bars closed by then
  python3 tests/t003_replay_csv.py FILE --quiet                            only the reproduction line

Exit status: 0 = ran (and reproduced, when a result is in the header and no override was given),
1 = ran but NOT reproduced, 2 = unreadable file.
"""
import argparse
import calendar
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import t003_reference_test as m  # noqa: E402

COLUMNS = ['time_epoch', 'time_server', 'open', 'high', 'low', 'close', 'tick_volume', 'spread', 'real_volume']


class CsvError(Exception):
    pass


def parse_server_time(text):
    """'YYYY.MM.DD HH:MM' -> epoch (server time handled as UTC, as MT5 datetime values are)"""
    try:
        tm = time.strptime(text.strip(), '%Y.%m.%d %H:%M')
    except ValueError:
        raise CsvError('bad time text %r (expected YYYY.MM.DD HH:MM)' % text)
    return calendar.timegm(tm)


def read_csv(path):
    """returns (header dict, bars list of m.Bar, rows list of tuples). Raises CsvError."""
    header = {}
    rows = []
    cols_seen = False
    try:
        with open(path, 'r', encoding='utf-8-sig') as fh:
            lines = fh.read().splitlines()
    except (OSError, UnicodeDecodeError) as exc:
        raise CsvError('cannot read %s: %s' % (path, exc))
    for ln, line in enumerate(lines, 1):
        line = line.strip()
        if not line:
            continue
        if line.startswith('#'):
            body = line[1:].strip()
            if '=' in body:
                k, v = body.split('=', 1)
                header[k.strip()] = v.strip()
            elif body.startswith('velo_t003_diag'):
                header['format'] = body
            continue
        if not cols_seen:
            if [c.strip() for c in line.split(',')] != COLUMNS:
                raise CsvError('line %d: expected the column header %s' % (ln, ','.join(COLUMNS)))
            cols_seen = True
            continue
        parts = line.split(',')
        if len(parts) != len(COLUMNS):
            raise CsvError('line %d: %d fields, expected %d' % (ln, len(parts), len(COLUMNS)))
        try:
            ep = int(parts[0])
            o, h, l, c = (float(parts[2]), float(parts[3]), float(parts[4]), float(parts[5]))
            tv, sp, rv = int(parts[6]), int(parts[7]), int(parts[8])
        except ValueError:
            raise CsvError('line %d: number expected' % ln)
        if parts[1].strip() != time.strftime('%Y.%m.%d %H:%M', time.gmtime(ep)):
            raise CsvError('line %d: time_server %r does not match time_epoch %d' % (ln, parts[1], ep))
        rows.append((ep, o, h, l, c, tv, sp, rv))
    if not cols_seen:
        raise CsvError('no column header line found')
    if not rows:
        raise CsvError('no bars')
    for i in range(1, len(rows)):
        if rows[i][0] <= rows[i - 1][0]:
            raise CsvError('bars are not strictly chronological at row %d' % (i + 1))
    if 'bars' in header and int(header['bars']) != len(rows):
        raise CsvError('header says %s bars, file has %d' % (header['bars'], len(rows)))
    bars = [m.Bar(r[0], r[2], r[3], r[4]) for r in rows]
    return header, bars, rows


def params_from_header(header, over):
    def geti(key, default):
        return int(header[key]) if key in header else default
    return m.Params(left=over.get('left') or geti('left', 2),
                    right=over.get('right') or geti('right', 2),
                    period=geti('period_seconds', m.PERIOD),
                    lookback=over.get('lookback') or geti('lookback', 300),
                    rebuild=over.get('rebuild') or geti('rebuild_input', 1000),
                    hard_cap=over.get('hard_cap') or geti('hard_cap', 5000))


def run_csv(path, over=None, asof=None):
    """evaluate the file. Returns (header, params, bars, ev, diag, reproduced) where reproduced is
    True/False/None (None: nothing to compare with, or parameters/as-of overridden)."""
    over = over or {}
    header, bars, _rows = read_csv(path)
    p = params_from_header(header, over)
    n = len(bars)
    if asof is not None:
        cut = [b for b in bars if b.time + p.period <= asof]
        bars = cut
        n = len(bars)
        if n == 0:
            raise CsvError('no bar is closed by the as-of time')
    ev = m.evaluate(bars, n, p)
    diag = m.diagnose(bars, n, p, ev)
    reproduced = None
    if 'result_flag' in header and not over and asof is None:
        reproduced = (header['result_flag'] == ev.flag and header.get('result_reason', '') == ev.reason)
    return header, p, bars, ev, diag, reproduced


def main(argv=None):
    ap = argparse.ArgumentParser(description='Replay a T003 diagnostic candle CSV in the Python model.')
    ap.add_argument('csv')
    ap.add_argument('--lookback', type=int)
    ap.add_argument('--rebuild', type=int)
    ap.add_argument('--left', type=int)
    ap.add_argument('--right', type=int)
    ap.add_argument('--hard-cap', dest='hard_cap', type=int)
    ap.add_argument('--asof', help='server time "YYYY.MM.DD HH:MM": only bars closed by then')
    ap.add_argument('--quiet', action='store_true')
    a = ap.parse_args(argv)
    over = dict((k, v) for k, v in (('lookback', a.lookback), ('rebuild', a.rebuild), ('left', a.left),
                                    ('right', a.right), ('hard_cap', a.hard_cap)) if v)
    try:
        asof = parse_server_time(a.asof) if a.asof else None
        header, p, bars, ev, diag, repro = run_csv(a.csv, over, asof)
    except CsvError as exc:
        print('ERROR: %s' % exc)
        return 2
    if not a.quiet:
        print('file: %s' % os.path.basename(a.csv))
        print('source: %s' % header.get('source', '?'))
        if header.get('source', '').upper().startswith('SYNTHETIC'):
            print('NOTE: this file is SYNTHETIC test data, not market data.')
        print('symbol %s, mode %s, asof_input %s, %d bars %s .. %s' % (
            header.get('symbol', '?'), header.get('mode', '?'), header.get('asof_input', '?'), len(bars),
            m.ts(bars[0].time), m.ts(bars[-1].time)))
        print('params: left %d right %d period %d lookback %d rebuild %d hard_cap %d%s' % (
            p.left, p.right, p.period, p.lookback, p.rebuild, p.hard_cap, ' (OVERRIDDEN)' if over or asof else ''))
        print('model result: FLAG=%s REASON=%s DIR=%s depths req %d eff %d b %d warm %d chk %d' % (
            ev.flag, ev.reason, m.reported_direction(ev), ev.r_req, ev.r_eff, ev.b_depth, ev.warm, ev.chk))
        if ev.note:
            print('note: %s' % ev.note)
        for line in m.diag_lines(diag):
            print(line)
    if repro is None:
        print('REPRODUCTION: not checked (%s)' % ('overridden parameters or as-of' if (over or asof) else 'no result in the header'))
        return 0
    if repro:
        print('REPRODUCTION: REPRODUCED - the model gives the same flag and reason as the EA (%s / %s)' % (ev.flag, ev.reason))
        return 0
    print('REPRODUCTION: NOT REPRODUCED - EA said %s / %s, the model says %s / %s. '
          'Model and MQL5 disagree on this series, or the file is incomplete: send the CSV.' % (
              header.get('result_flag'), header.get('result_reason'), ev.flag, ev.reason))
    return 1


if __name__ == '__main__':
    sys.exit(main())
